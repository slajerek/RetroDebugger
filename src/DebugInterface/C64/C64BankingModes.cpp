int C64BankingMode(u8 exrom, u8 game, u8 port)
{
	return ((exrom & 1) << 4) | ((game & 1) << 3) | (port & 0x07);
}

C64BankEntry C64BankingEntry(int mode, int region)
{
	if (mode < 0 || mode >= 32 || region < 0 || region >= C64BANK_NUM_REGIONS)
		return C64BANK_OPEN;
	return memoryModes[mode][region];
}

int C64BankingRegion(u16 addr)
{
	if (addr < 0x8000) return -1;
	if (addr < 0xA000) return C64BANK_REGION_8000;
	if (addr < 0xC000) return C64BANK_REGION_A000;
	if (addr < 0xD000) return C64BANK_REGION_C000;
	if (addr < 0xE000) return C64BANK_REGION_D000;
	return C64BANK_REGION_E000;
}

bool C64BankingIsUltimax(int mode)
{
	return mode >= 16 && mode <= 23;
}

const char *C64BankEntryName(C64BankEntry entry)
{
	static const char *names[] = { "RAM", "BASIC ROM", "KERNAL ROM", "CHAR ROM", "I/O", "CART ROM LO", "CART ROM HI", "OPEN" };
	return entry <= C64BANK_OPEN ? names[entry] : "?";
}

const char *C64BankRegionName(int region)
{
	static const char *names[] = { "$8000-$9FFF", "$A000-$BFFF", "$C000-$CFFF", "$D000-$DFFF", "$E000-$FFFF" };
	return region >= 0 && region < C64BANK_NUM_REGIONS ? names[region] : "?";
}
